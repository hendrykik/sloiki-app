CREATE TABLE users
(
    id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login varchar(255) NOT NULL,
    password varchar(255) NOT NULL
);

CREATE TABLE calendar_events
(
    id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_user int REFERENCES users(id),
    date date NOT NULL,
    title varchar(255) NOT NULL,
    description text
);

